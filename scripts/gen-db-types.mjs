#!/usr/bin/env node
// Generates src/server/db/database.types.ts (Supabase/PostgREST type shape)
// by introspecting the local test database started by scripts/local-db/start.sh.
// Equivalent in output shape to `supabase gen types typescript` for the
// `public` schema; kept in-repo so types can be regenerated without extra
// Docker images. CI regenerates and fails on drift.
import fs from "node:fs";
import path from "node:path";
import pg from "pg";

const root = path.resolve(import.meta.dirname, "..");
const envFile = path.join(root, ".env.test.local");
if (!process.env.TEST_DATABASE_URL && fs.existsSync(envFile)) {
  for (const line of fs.readFileSync(envFile, "utf8").split("\n")) {
    const m = /^([A-Z0-9_]+)=(.*)$/.exec(line.trim());
    if (m) process.env[m[1]] ??= m[2];
  }
}
if (!process.env.TEST_DATABASE_URL) {
  console.error("TEST_DATABASE_URL missing. Run `pnpm db:local:start` first.");
  process.exit(1);
}

const client = new pg.Client({ connectionString: process.env.TEST_DATABASE_URL });
await client.connect();

const enums = (
  await client.query(`
    select t.typname as name, array_agg(e.enumlabel::text order by e.enumsortorder) as labels
    from pg_type t join pg_enum e on e.enumtypid = t.oid
    join pg_namespace n on n.oid = t.typnamespace
    where n.nspname = 'public' group by t.typname order by t.typname`)
).rows;
const enumNames = new Set(enums.map((e) => e.name));

const columns = (
  await client.query(`
    select c.relname as table, a.attname as column, a.attnum,
           format_type(a.atttypid, a.atttypmod) as type,
           t.typname as udt, tn.nspname as udt_schema,
           not a.attnotnull as nullable,
           (a.atthasdef or a.attidentity <> '' or a.attgenerated <> '') as has_default,
           a.attidentity = 'a' as identity_always
    from pg_attribute a
    join pg_class c on c.oid = a.attrelid
    join pg_namespace n on n.oid = c.relnamespace
    join pg_type t on t.oid = a.atttypid
    join pg_namespace tn on tn.oid = t.typnamespace
    where n.nspname = 'public' and c.relkind = 'r' and a.attnum > 0 and not a.attisdropped
    order by c.relname, a.attnum`)
).rows;

const fks = (
  await client.query(`
    select con.conname as name, src.relname as table, dst.relname as referenced,
           array(select a.attname::text from unnest(con.conkey) with ordinality k(n, i)
                 join pg_attribute a on a.attrelid = con.conrelid and a.attnum = k.n order by k.i) as columns,
           array(select a.attname::text from unnest(con.confkey) with ordinality k(n, i)
                 join pg_attribute a on a.attrelid = con.confrelid and a.attnum = k.n order by k.i) as referenced_columns,
           (select count(*) from pg_constraint u
              where u.conrelid = con.conrelid and u.contype in ('u', 'p')
                and (select array_agg(x order by x) from unnest(u.conkey) x) = (select array_agg(x order by x) from unnest(con.conkey) x)) > 0 as one_to_one
    from pg_constraint con
    join pg_class src on src.oid = con.conrelid
    join pg_class dst on dst.oid = con.confrelid
    join pg_namespace n on n.oid = src.relnamespace
    where con.contype = 'f' and n.nspname = 'public'
    order by src.relname, con.conname`)
).rows;

const functions = (
  await client.query(`
    select p.proname as name,
           coalesce(p.proargnames::text[], '{}') as arg_names,
           coalesce(array(select format_type(x, null) from unnest(p.proargtypes) x), '{}') as arg_types,
           p.pronargdefaults as n_defaults,
           p.proretset as returns_set,
           format_type(p.prorettype, null) as return_type,
           coalesce(p.proallargtypes::regtype[]::text[], '{}') as all_types,
           coalesce(p.proargmodes::text[], '{}') as modes
    from pg_proc p join pg_namespace n on n.oid = p.pronamespace
    where n.nspname = 'public' and p.prokind = 'f'
    order by p.proname`)
).rows;

await client.end();

function tsType(sqlType) {
  const base = sqlType.replace(/^public\./, "").replace(/\[\]$/, "");
  const isArray = sqlType.endsWith("[]");
  let t;
  if (enumNames.has(base)) t = `Database["public"]["Enums"]["${base}"]`;
  else if (/^(smallint|integer|bigint|numeric|real|double precision)/.test(base)) t = "number";
  else if (base === "boolean") t = "boolean";
  else if (base === "json" || base === "jsonb") t = "Json";
  else t = "string";
  return isArray ? `${t}[]` : t;
}

const byTable = new Map();
for (const col of columns) {
  if (!byTable.has(col.table)) byTable.set(col.table, []);
  byTable.get(col.table).push(col);
}

const ind = (n) => " ".repeat(n);
let out = "";
out += "// Generated by scripts/gen-db-types.mjs from supabase/migrations. Do not edit by hand.\n";
out += "export type Json = string | number | boolean | null | { [key: string]: Json | undefined } | Json[];\n\n";
out += "export type Database = {\n";
out += `${ind(2)}__InternalSupabase: {\n${ind(4)}PostgrestVersion: "13";\n${ind(2)}};\n`;
out += `${ind(2)}public: {\n${ind(4)}Tables: {\n`;
for (const [table, cols] of byTable) {
  out += `${ind(6)}${table}: {\n`;
  out += `${ind(8)}Row: {\n`;
  for (const c of cols) out += `${ind(10)}${c.column}: ${tsType(c.type)}${c.nullable ? " | null" : ""};\n`;
  out += `${ind(8)}};\n${ind(8)}Insert: {\n`;
  for (const c of cols) {
    if (c.identity_always) out += `${ind(10)}${c.column}?: never;\n`;
    else out += `${ind(10)}${c.column}${c.nullable || c.has_default ? "?" : ""}: ${tsType(c.type)}${c.nullable ? " | null" : ""};\n`;
  }
  out += `${ind(8)}};\n${ind(8)}Update: {\n`;
  for (const c of cols) {
    if (c.identity_always) out += `${ind(10)}${c.column}?: never;\n`;
    else out += `${ind(10)}${c.column}?: ${tsType(c.type)}${c.nullable ? " | null" : ""};\n`;
  }
  out += `${ind(8)}};\n${ind(8)}Relationships: [\n`;
  for (const fk of fks.filter((f) => f.table === table)) {
    out += `${ind(10)}{\n`;
    out += `${ind(12)}foreignKeyName: "${fk.name}";\n`;
    out += `${ind(12)}columns: [${fk.columns.map((c) => `"${c}"`).join(", ")}];\n`;
    out += `${ind(12)}isOneToOne: ${fk.one_to_one};\n`;
    out += `${ind(12)}referencedRelation: "${fk.referenced}";\n`;
    out += `${ind(12)}referencedColumns: [${fk.referenced_columns.map((c) => `"${c}"`).join(", ")}];\n`;
    out += `${ind(10)}},\n`;
  }
  out += `${ind(8)}];\n${ind(6)}};\n`;
}
out += `${ind(4)}};\n${ind(4)}Views: {\n${ind(6)}[_ in never]: never;\n${ind(4)}};\n${ind(4)}Functions: {\n`;
for (const fn of functions) {
  const modes = fn.modes;
  const names = fn.arg_names;
  const allTypes = fn.all_types.length ? fn.all_types : fn.arg_types;
  const inArgs = [];
  const outCols = [];
  allTypes.forEach((type, i) => {
    const mode = modes[i] ?? "i";
    if (mode === "i" || mode === "b") inArgs.push({ name: names[i], type });
    if (mode === "o" || mode === "t" || mode === "b") outCols.push({ name: names[i], type });
  });
  const firstDefault = inArgs.length - fn.n_defaults;
  out += `${ind(6)}${fn.name}: {\n${ind(8)}Args: `;
  if (inArgs.length === 0) out += "never;\n";
  else {
    out += "{\n";
    inArgs.forEach((a, i) => {
      out += `${ind(10)}${a.name}${i >= firstDefault ? "?" : ""}: ${tsType(a.type)};\n`;
    });
    out += `${ind(8)}};\n`;
  }
  let ret;
  if (outCols.length) {
    ret = `{\n${outCols.map((c) => `${ind(10)}${c.name}: ${tsType(c.type)};`).join("\n")}\n${ind(8)}}[]`;
  } else if (fn.return_type === "void") ret = "undefined";
  else ret = tsType(fn.return_type) + (fn.returns_set ? "[]" : "");
  out += `${ind(8)}Returns: ${ret};\n${ind(6)}};\n`;
}
out += `${ind(4)}};\n${ind(4)}Enums: {\n`;
for (const e of enums) out += `${ind(6)}${e.name}: ${e.labels.map((l) => `"${l}"`).join(" | ")};\n`;
out += `${ind(4)}};\n${ind(4)}CompositeTypes: {\n${ind(6)}[_ in never]: never;\n${ind(4)}};\n${ind(2)}};\n};\n\n`;
out += `type PublicSchema = Database["public"];\n`;
out += `export type Tables<T extends keyof PublicSchema["Tables"]> = PublicSchema["Tables"][T]["Row"];\n`;
out += `export type TablesInsert<T extends keyof PublicSchema["Tables"]> = PublicSchema["Tables"][T]["Insert"];\n`;
out += `export type TablesUpdate<T extends keyof PublicSchema["Tables"]> = PublicSchema["Tables"][T]["Update"];\n`;
out += `export type Enums<T extends keyof PublicSchema["Enums"]> = PublicSchema["Enums"][T];\n`;

const target = path.join(root, "src/server/db/database.types.ts");
fs.writeFileSync(target, out);
console.log(`Wrote ${path.relative(root, target)}`);
