#!/usr/bin/env bash
# Starts a disposable local database stack for RLS and integration tests:
#   - supabase/postgres (the same engine image Supabase hosts; ships the
#     anon/authenticated/service_role roles, auth.jwt() and Supabase's default
#     grants, so missing REVOKEs are caught)
#   - PostgREST (the Supabase Data API), verifying HS256 JWTs signed with a
#     per-run random secret. Tests mint Clerk-shaped claims with that secret.
# Writes connection details to .env.test.local (gitignored). Nothing here is
# used outside local/CI testing.
set -euo pipefail

ROOT="$(cd "$(dirname "${BASH_SOURCE[0]}")/../.." && pwd)"
PG_IMAGE="${PG_IMAGE:-supabase/postgres:17.11.0.006}"
PGRST_IMAGE="${PGRST_IMAGE:-postgrest/postgrest:v16.5}"
NET=parmarpro-test
DB=parmarpro-test-db
API=parmarpro-test-api
DB_PORT="${TEST_DB_PORT:-54329}"
API_PORT="${TEST_API_PORT:-54328}"
DB_PASSWORD="$(openssl rand -hex 16)"
JWT_SECRET="$(openssl rand -hex 32)"

docker rm -f "$API" "$DB" >/dev/null 2>&1 || true
docker network create "$NET" >/dev/null 2>&1 || true

docker run -d --name "$DB" --network "$NET" -p "127.0.0.1:${DB_PORT}:5432" \
  -e POSTGRES_PASSWORD="$DB_PASSWORD" \
  -e JWT_SECRET="$JWT_SECRET" -e JWT_EXP=3600 \
  "$PG_IMAGE" postgres -c config_file=/etc/postgresql/postgresql.conf >/dev/null

echo "Waiting for Postgres..."
for _ in $(seq 1 90); do
  if docker exec "$DB" pg_isready -U postgres -h 127.0.0.1 >/dev/null 2>&1; then break; fi
  sleep 1
done
# The image runs its init scripts after the server first accepts connections.
for _ in $(seq 1 90); do
  if docker exec -e PGPASSWORD="$DB_PASSWORD" "$DB" psql -U postgres -h 127.0.0.1 -d postgres -tAc \
      "select 1 from pg_roles where rolname='authenticator'" 2>/dev/null | grep -q 1; then break; fi
  sleep 1
done
sleep 2

# The Supabase CLI sets the PostgREST login role's password the same way.
docker exec "$DB" psql -v ON_ERROR_STOP=1 -q -U supabase_admin -d postgres \
  -c "alter role authenticator with password '${DB_PASSWORD}'" >/dev/null

echo "Applying migrations as the 'postgres' role (as Supabase does)..."
for f in "$ROOT"/supabase/migrations/*.sql; do
  [ -e "$f" ] || continue
  echo "  - $(basename "$f")"
  docker exec -i -e PGPASSWORD="$DB_PASSWORD" "$DB" \
    psql -v ON_ERROR_STOP=1 -q -U postgres -h 127.0.0.1 -d postgres < "$f"
done

docker run -d --name "$API" --network "$NET" -p "127.0.0.1:${API_PORT}:3000" \
  -e PGRST_DB_URI="postgres://authenticator:${DB_PASSWORD}@${DB}:5432/postgres" \
  -e PGRST_DB_SCHEMAS=public \
  -e PGRST_DB_ANON_ROLE=anon \
  -e PGRST_JWT_SECRET="$JWT_SECRET" \
  -e PGRST_DB_USE_LEGACY_GUCS=false \
  -e PGRST_DB_MAX_ROWS=1000 \
  "$PGRST_IMAGE" >/dev/null

echo "Waiting for PostgREST..."
for _ in $(seq 1 60); do
  if curl -s -o /dev/null "http://127.0.0.1:${API_PORT}/"; then break; fi
  sleep 1
done

cat > "$ROOT/.env.test.local" <<ENV
# Generated by scripts/local-db/start.sh. Local disposable test stack only.
TEST_DATABASE_URL=postgres://postgres:${DB_PASSWORD}@127.0.0.1:${DB_PORT}/postgres
TEST_POSTGREST_URL=http://127.0.0.1:${API_PORT}
TEST_JWT_SECRET=${JWT_SECRET}
ENV
echo "Local test stack ready (details in .env.test.local)."
