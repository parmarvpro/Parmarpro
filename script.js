// Counter animation for stats
function animateCounter(element, target, duration) {
    let current = 0;
    const increment = target / (duration / 16); // 60fps

    const timer = setInterval(() => {
        current += increment;
        if (current >= target) {
            element.textContent = formatNumber(target);
            clearInterval(timer);
        } else {
            element.textContent = formatNumber(Math.floor(current));
        }
    }, 16);
}

function formatNumber(num) {
    if (num >= 10000000) {
        return '₹' + (num / 10000000).toFixed(0) + 'Cr+';
    } else if (num >= 100000) {
        return (num / 100000).toFixed(0) + 'L+';
    } else if (num >= 1000) {
        return (num / 1000).toFixed(0) + 'K+';
    }
    return num.toString();
}

// Animate stats when they come into view
const statsObserver = new IntersectionObserver((entries) => {
    entries.forEach(entry => {
        if (entry.isIntersecting && !entry.target.classList.contains('animated')) {
            entry.target.classList.add('animated');
            const statElements = entry.target.querySelectorAll('.stat h3');

            // Simulate counter animation
            setTimeout(() => {
                statElements[0].textContent = '1M+';
                statElements[1].textContent = '5000+';
                statElements[2].textContent = '₹500Cr+';
            }, 200);
        }
    });
}, { threshold: 0.5 });

const heroStats = document.querySelector('.hero-stats');
if (heroStats) {
    statsObserver.observe(heroStats);
}

